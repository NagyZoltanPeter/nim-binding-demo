import std/[strutils, os]

# Default path relative to libnimdemo when built via nimble buildlib
const defaultOutRel* = "bindings/cpp_binding/include/demolib/generated_api.hpp"

proc ensureParentDir(path: string) =
  let dir = splitFile(path).dir
  if dir.len > 0 and not dirExists(dir):
    createDir(dir)

proc findWorkspaceRoot(): string =
  ## Try to locate the repository root by searching upwards for the bindings dir.
  var cur = getCurrentDir()
  for _ in 0..6:
    if dirExists(joinPath(cur, "bindings/cpp_binding/include/demolib")):
      return cur
    let parent = parentDir(cur)
    if parent == cur: break
    cur = parent
  return getCurrentDir()

proc emitCppSnippet*(path: string, content: string, append = true) =
  ## Writes or appends a C++ snippet to file.
  ## Ensures parent dir exists; if file is new, writes a small header banner.
  var outPath = path
  let root = findWorkspaceRoot()
  if outPath.len == 0:
    outPath = joinPath(root, defaultOutRel)
  elif not outPath.isAbsolute:
    outPath = joinPath(root, outPath)
  ensureParentDir(outPath)
  echo "emitCpp -> " & outPath
  if fileExists(outPath):
    if append:
      let existing = readFile(outPath)
      let sep = if existing.len > 0 and existing[^1] != '\n': "\n\n" else: "\n"
      writeFile(outPath, existing & sep & content)
    else:
      writeFile(outPath, content)
  else:
    let prolog = """// Auto-generated file. Do not edit by hand.
// Generated by Nim ffi macro with -d:emitCpp

"""
    writeFile(outPath, prolog & content)

proc gen_cpp_api_interface*(procName: string, argType: string, argName: string, retType: string): string =
  ## Generate a C++ wrapper snippet for an FFI-exposed Nim proc.
  let pn = procName
  let at = argType
  let an = (if argName.len > 0: argName else: "arg")
  let rt = retType

  proc genZeroVoid(): string =
    result = """inline ApiCallResultCode %NAME%() {
    void* resultBuffer = nullptr;
    int resultLen = 0;
    char* errorDesc = nullptr;
    auto result = syncApiCall("%NAME%", nullptr, 0, &resultBuffer, &resultLen, &errorDesc);
    if (result != ApiCallResultCode::NIMAPI_OK) {
        std::string errorMsg(errorDesc ? errorDesc : "Unknown error");
        deallocateArgBuffer(errorDesc);
        std::cerr << "Api call error: " << static_cast<int>(result) << " # " << errorMsg << std::endl;
    }
    if (resultBuffer) { deallocateArgBuffer(resultBuffer); }
    return static_cast<ApiCallResultCode>(result);
}
""".replace("%NAME%", pn)

  proc genZeroSeqString(): string =
    result = """inline ApiResult<std::vector<std::string>> %NAME%() {
    void* returnBuffer = nullptr;
    int returnLen = 0;
    char* errorDesc = nullptr;
    auto result = syncApiCall("%NAME%", nullptr, 0, &returnBuffer, &returnLen, &errorDesc);
    if (result != ApiCallResultCode::NIMAPI_OK) {
        std::string errorMsg(errorDesc ? errorDesc : "Unknown error");
        if (errorDesc) { deallocateArgBuffer(errorDesc); }
        std::cerr << "Api call error: " << errorMsg << std::endl;
        return tl::unexpected(ApiError{result, errorMsg});
    }
    std::vector<std::string> out;
    if (returnBuffer && returnLen > 0) {
        ApiStrings decoded;
        if (decoded.ParseFromArray(returnBuffer, returnLen)) {
            for (const auto& s : decoded.value()) { out.push_back(s); }
        }
        deallocateArgBuffer(returnBuffer);
    }
    return out;
}
""".replace("%NAME%", pn)

  proc genOneArg(): string =
    var ser: string
    if at.len > 0:
      ser = """const int sizeRequired = static_cast<int>(%ARG%.ByteSizeLong());
    void* argBuffer = allocateArgBuffer(sizeRequired);
    if (!%ARG%.SerializeToArray(argBuffer, sizeRequired)) {
        std::cerr << "Failed to serialize argument for %NAME%" << std::endl;
        deallocateArgBuffer(argBuffer);
        return ApiCallResultCode::NIMAPI_FAIL;
    }
    return (ApiCallResultCode)asyncApiCall("%NAME%", argBuffer, sizeRequired);
    // Ownership of argBuffer is transferred to the Nim library.
"""
      ser = ser.replace("%ARG%", an)
    else:
      ser = "return (ApiCallResultCode)asyncApiCall(\"%NAME%\", nullptr, 0);\n"
    result = ("""inline ApiCallResultCode %NAME%(const %ARGTYPE%& %ARGNAME%) {
    %SER%
}
"""
      .replace("%NAME%", pn)
      .replace("%ARGTYPE%", if at.len > 0: at else: "void")
      .replace("%ARGNAME%", if at.len > 0: an else: "")
      .replace("%SER%", ser.replace("%NAME%", pn)))

  if at.len == 0:
    if rt == "void":
      return genZeroVoid()
    elif rt == "seq[string]":
      return genZeroSeqString()
    else:
      return genZeroVoid()
  else:
    return genOneArg()
